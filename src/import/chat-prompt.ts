/**
 * Prompt for ChatGPT: whatever the person sends (links, screenshots, a table,
 * a file or plain words) comes back as "Название | Цена | Ссылка" lines that
 * parseChatList() reads.
 */
export const CHAT_PROMPT = `Помоги перенести список желаемых подарков в вишлист. Я пришлю товары в любом виде: ссылки, скриншоты корзины или страниц, таблицу, файл или просто опишу словами.

Найди все товары и выведи их одним блоком кода, по одному товару на строку, строго в формате:
Название | Цена | Ссылка

Правила:
- Название — короткое понятное название вещи на русском, 2–6 слов. Бренд и модель можно оставить, например «Наушники Sony WH-1000XM5».
- Цена — только число в рублях, без пробелов и знака ₽, например 2490. Если на скриншоте есть цена со скидкой и старая цена, бери цену со скидкой. Диапазон пиши так: 1000-3000. Если цены нет — оставь поле пустым.
- Ссылка — полная ссылка на этот товар, начинается с https://. Короткие ссылки вида ozon.ru/t/… оставляй как есть. Если ссылки нет — оставь поле пустым.
- Не придумывай названия, цены и ссылки: бери только то, что есть в моих данных или на открытой странице товара.
- Не путай цены и ссылки между товарами, сохраняй порядок.
- Обработай все товары, а не только первые.
- Без заголовка, нумерации, картинок, пояснений и итоговой суммы — только строки товаров в блоке кода.`;
